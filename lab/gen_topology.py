#!/usr/bin/env python3
"""Generate the containerlab topology from the same intent file the pipeline uses,
so the lab cabling can never drift from the source of truth.

  python lab/gen_topology.py > lab/topology.clab.yml
"""
import copy
import os
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from fabric.render import ROOT, load_intent  # noqa: E402

KINDS = {
    "nxos": {"kind": "cisco_n9kv", "image": "vrnetlab/cisco_n9kv:9300-10.4.8.M"},
    # 4 vCPUs (Juniper's minimum). More does not help: the vJunos data plane busy-polls every
    # vCPU it is given (measured ~600% of 6), so the control plane stays starved either way.
    # VJUNOS_SMP needs vrnetlab patched to read it (lab/setup_vm.sh does this).
    "junos": {"kind": "juniper_vjunosswitch", "image": "vrnetlab/juniper_vjunos-switch:26.2R1.7",
              "env": {"VJUNOS_SMP": "4"}},
}
# How many switch VMs boot at once; later ones wait for earlier ones to be healthy.
# vJunos wants 4 vCPUs to boot: on an 8-vCPU host use 2 (3 at once never finished),
# on the 16-vCPU host all 6 boot together. Override with FABRIC_PARALLEL_BOOTS.
PARALLEL_BOOTS = int(os.environ.get("FABRIC_PARALLEL_BOOTS", "6"))


def clab_iface(platform: str, name: str) -> str:
    """containerlab wires VMs by ethN: NX-OS Ethernet1/N -> ethN, Junos ge-0/0/N -> eth(N+1)."""
    if platform == "nxos":
        return f"eth{int(name.split('/')[-1])}"
    return f"eth{int(name.split('/')[-1]) + 1}"


def lab_hosts(fab) -> list[dict]:
    """One test host per leaf host port: hostN gets .10+N in its VLAN's subnet."""
    vnis = {v.vlan: v for v in fab.vnis}
    hosts, n = [], 0
    for d in fab.devices:
        for port in d.host_ports:
            n += 1
            gw = vnis[port.vlan].gateway
            hosts.append({"name": f"host{n}", "ip": str(gw.network[10 + n]), "prefixlen": gw.network.prefixlen,
                          "gateway": str(gw.ip), "vlan": port.vlan, "vrf": vnis[port.vlan].vrf,
                          "leaf": d.name, "platform": d.platform, "interface": port.interface})
    return hosts


def main(intent=ROOT / "intent" / "fabric.yml"):
    fab = load_intent(intent)
    by_name = {d.name: d for d in fab.devices}
    nodes, links = {}, []
    for i, d in enumerate(fab.devices):
        nodes[d.name] = {**copy.deepcopy(KINDS[d.platform]), "mgmt-ipv4": str(d.mgmt_ip)}
        if i >= PARALLEL_BOOTS:
            prev = fab.devices[i - PARALLEL_BOOTS].name
            nodes[d.name]["stages"] = {"create": {"wait-for": [{"node": prev, "stage": "healthy"}]}}
    for link in fab.links:
        (a, ai), (b, bi) = link.ends()
        links.append({"endpoints": [f"{a}:{clab_iface(by_name[a].platform, ai)}",
                                    f"{b}:{clab_iface(by_name[b].platform, bi)}"]})
    for h in lab_hosts(fab):
        nodes[h["name"]] = {
            "kind": "linux", "image": "alpine:3.20",
            "exec": [f"ip addr add {h['ip']}/{h['prefixlen']} dev eth1",
                     "ip link set eth1 mtu 1500 up", f"ip route replace default via {h['gateway']}"],
        }
        links.append({"endpoints": [f"{h['leaf']}:{clab_iface(h['platform'], h['interface'])}", f"{h['name']}:eth1"]})
    topo = {"name": fab.fabric.name,
            "mgmt": {"network": "clab-mgmt", "ipv4-subnet": "172.20.20.0/24"},
            "topology": {"nodes": nodes, "links": links}}
    print(f"# GENERATED by lab/gen_topology.py from {Path(intent).relative_to(ROOT) if Path(intent).is_absolute() else intent} - do not edit by hand")
    print(yaml.safe_dump(topo, sort_keys=False))


if __name__ == "__main__":
    main(*sys.argv[1:])
